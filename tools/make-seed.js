// Builds supabase/02_seed.sql from js/seed-data.js
// Run from the repo folder:  node tools/make-seed.js
const fs = require('fs');
const path = require('path');
const SEED = require(path.join(__dirname, '..', 'js', 'seed-data.js'));

const q = v => v === null || v === undefined ? 'null'
  : typeof v === 'number' ? String(v)
  : typeof v === 'boolean' ? String(v)
  : `'${String(v).replace(/'/g, "''")}'`;
const j = v => `${q(JSON.stringify(v))}::jsonb`;
const arr = a => `${q('{' + a.map(x => '"' + String(x).replace(/"/g, '\\"') + '"').join(',') + '}')}::text[]`;

let out = `-- ============================================================
-- PARSLEY'S FARM v6 — Starting data (farm state on 12 Nov 2026)
-- Generated by tools/make-seed.js from js/seed-data.js. Run once after 01_schema.sql.
-- ============================================================
begin;
`;

out += '\n-- crops\n';
SEED.crops.forEach(c => {
  out += `insert into public.crops (id,name,name_sw,color,kind,count_from,stages,feeds,to_remove,sort) values (${q(c.id)},${q(c.name)},${q(c.name_sw)},${q(c.color)},${q(c.kind)},${q(c.count_from)},${j(c.stages)},${j(c.feeds)},${q(!!c.to_remove)},${q(c.sort)}) on conflict (id) do nothing;\n`;
});

out += '\n-- blocks\n';
SEED.blocks.forEach(b => {
  out += `insert into public.blocks (id,farm,code,label,kind,was,top_note,bottom_note,subs,extras,short_beds,gh_range,sub_notes,sort) values (${q(b.id)},${q(b.farm)},${q(b.code)},${q(b.label)},${q(b.kind)},${q(b.was)},${q(b.top_note)},${q(b.bottom_note)},${j(b.subs)},${j(b.extras)},${j(b.short_beds)},${b.gh_range ? j(b.gh_range) : 'null'},${j(b.sub_notes)},${q(b.sort)}) on conflict (id) do nothing;\n`;
});

out += '\n-- beds\n';
SEED.beds.forEach(b => {
  out += `insert into public.beds (id,farm,block,num,crop,plant_date,approx,note,drip,poor,needs_check,seedbed,feeds_done,active) values (${q(b.id)},${q(b.farm)},${q(b.block)},${q(b.num)},${q(b.crop)},${b.plant_date ? q(b.plant_date) + '::date' : 'null'},${q(b.approx)},${q(b.note)},${q(b.drip)},${q(b.poor)},${q(b.needs_check)},${q(b.seedbed)},${arr(b.feeds_done)},${q(b.active)}) on conflict (id) do nothing;\n`;
});

out += '\n-- records\n';
SEED.records.forEach(r => {
  out += `insert into public.records (date,type,title,details,where_text,targets,done_by,created_by) values (${q(r.date)}::date,${q(r.type)},${q(r.title)},${q(r.details)},${q(r.where_text)},${arr(r.targets)},${q(r.done_by)},'setup');\n`;
});

out += '\n-- regular bills\n';
SEED.bills.forEach(b => {
  out += `insert into public.bills (name,category,amount,active,note,sort) values (${q(b.name)},${q(b.category)},${q(b.amount)},${q(b.active)},${q(b.note)},${q(b.sort)});\n`;
});

out += '\n-- products\n';
SEED.products.forEach(p => {
  out += `insert into public.products (name,type,active_ingredient,phi_days) values (${q(p.name)},${q(p.type)},${q(p.active_ingredient)},${q(p.phi_days)});\n`;
});

out += '\ncommit;\n';
fs.writeFileSync(path.join(__dirname, '..', 'supabase', '02_seed.sql'), out);
console.log(`Wrote supabase/02_seed.sql: ${SEED.crops.length} crops, ${SEED.blocks.length} blocks, ${SEED.beds.length} beds`);
